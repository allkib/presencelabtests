"""COCO-17 keypoint layout used by Ultralytics YOLO pose models."""

from __future__ import annotations

from enum import IntEnum


class KP(IntEnum):
    NOSE = 0
    LEFT_EYE = 1
    RIGHT_EYE = 2
    LEFT_EAR = 3
    RIGHT_EAR = 4
    LEFT_SHOULDER = 5
    RIGHT_SHOULDER = 6
    LEFT_ELBOW = 7
    RIGHT_ELBOW = 8
    LEFT_WRIST = 9
    RIGHT_WRIST = 10
    LEFT_HIP = 11
    RIGHT_HIP = 12
    LEFT_KNEE = 13
    RIGHT_KNEE = 14
    LEFT_ANKLE = 15
    RIGHT_ANKLE = 16


NUM_KEYPOINTS = len(KP)

SKELETON: tuple[tuple[KP, KP], ...] = (
    (KP.LEFT_ANKLE, KP.LEFT_KNEE),
    (KP.LEFT_KNEE, KP.LEFT_HIP),
    (KP.RIGHT_ANKLE, KP.RIGHT_KNEE),
    (KP.RIGHT_KNEE, KP.RIGHT_HIP),
    (KP.LEFT_HIP, KP.RIGHT_HIP),
    (KP.LEFT_SHOULDER, KP.LEFT_HIP),
    (KP.RIGHT_SHOULDER, KP.RIGHT_HIP),
    (KP.LEFT_SHOULDER, KP.RIGHT_SHOULDER),
    (KP.LEFT_SHOULDER, KP.LEFT_ELBOW),
    (KP.RIGHT_SHOULDER, KP.RIGHT_ELBOW),
    (KP.LEFT_ELBOW, KP.LEFT_WRIST),
    (KP.RIGHT_ELBOW, KP.RIGHT_WRIST),
    (KP.LEFT_EYE, KP.RIGHT_EYE),
    (KP.NOSE, KP.LEFT_EYE),
    (KP.NOSE, KP.RIGHT_EYE),
    (KP.LEFT_EYE, KP.LEFT_EAR),
    (KP.RIGHT_EYE, KP.RIGHT_EAR),
)
